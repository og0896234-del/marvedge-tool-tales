// Regenerates src/lib/country-shapes.ts: fitted, simplified SVG silhouettes
// from Natural Earth (world-atlas 110m) TopoJSON. Run with: node scripts/gen-country-shapes.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const TOPO = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-110m.json", import.meta.url)));
const FC = feature(TOPO, TOPO.objects.countries);
const BY_ID = new Map(FC.features.map((f) => [String(f.id), f]));

// id -> ISO numeric codes whose outlines should be fitted together into one card,
// plus a mainland bbox: overseas territories (French Guiana, Alaska, Hawaii…) would
// otherwise blow the fitted bounds wide and shrink the part people recognise.
const TARGETS = {
  india: { ids: ["356"], bbox: [68, 6, 98, 37] },
  usa: { ids: ["840", "124"], bbox: [-141, 24, -52, 72] },
  oceania: { ids: ["036", "554"], bbox: [112, -48, 179, -10] },
  latam: { ids: ["076", "484"], bbox: [-118, -34, -34, 33] },
  africa: { ids: ["710", "818"], bbox: [16, -35, 37, 32] },
  // UK + the Schengen states our presets actually cover.
  europe: { ids: ["826", "250", "276", "724", "380", "528", "056", "040", "756", "620", "372"], bbox: [-11, 36, 25, 62] },
  mideast: { ids: ["682", "784", "634", "512", "414"], bbox: [34, 12, 62, 43] }, // Saudi, UAE, Qatar, Oman, Kuwait
};


const centroid = (r) => {
  let x = 0, y = 0;
  for (const p of r) { x += p[0]; y += p[1]; }
  return [x / r.length, y / r.length];
};
const inBox = (pt, b) => pt[0] >= b[0] && pt[0] <= b[2] && pt[1] >= b[1] && pt[1] <= b[3];
const clip = (geom, b) => {
  if (geom.type === "Polygon") {
    const rings = geom.coordinates.filter((r) => inBox(centroid(r), b));
    return rings.length ? { ...geom, coordinates: rings } : null;
  }
  if (geom.type === "MultiPolygon") {
    const polys = geom.coordinates
      .map((p) => p.filter((r) => inBox(centroid(r), b)))
      .filter((p) => p.length);
    return polys.length ? { ...geom, coordinates: polys } : null;
  }
  return geom;
};


const rdp = (pts, eps) => {
  if (pts.length < 3) return pts;
  const dist = (p, a, b) => {
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const len = Math.hypot(dx, dy);
    if (!len) return Math.hypot(p[0] - a[0], p[1] - a[1]);
    const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (len * len)));
    return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
  };
  let worst = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = dist(pts[i], pts[0], pts[pts.length - 1]);
    if (d > worst) { worst = d; at = i; }
  }
  if (worst > eps) {
    const a = rdp(pts.slice(0, at + 1), eps);
    const b = rdp(pts.slice(at), eps);
    return a.slice(0, -1).concat(b);
  }
  return [pts[0], pts[pts.length - 1]];
};

// d3 emits only M/L/Z here, so a flat token scan is enough to split rings out.
const parse = (d) => {
  const rings = [];
  let cur = null;
  for (const m of d.matchAll(/([MLZ])([^MLZ]*)/g)) {
    const nums = m[2].trim().split(/[\s,]+/).filter(Boolean).map(Number);
    if (m[1] === "M") { if (cur) rings.push(cur); cur = []; }
    else if (m[1] === "L") for (let i = 0; i < nums.length; i += 2) cur.push([nums[i], nums[i + 1]]);
  }
  if (cur) rings.push(cur);
  return rings;
};

const shape = ({ ids, bbox }, eps = 0.22) => {
  const feats = ids
    .map((id) => {
      // world-atlas writes ISO numeric codes zero-padded to three digits ("056").
      const f = BY_ID.get(id) || BY_ID.get(id.padStart(3, "0"));
      if (!f) throw new Error(`no geometry for id ${id} — not in world-atlas countries-110m`);
      return { type: "Feature", properties: {}, geometry: clip(f.geometry, bbox) };
    })

    .filter((f) => f.geometry);
  if (!feats.length) throw new Error(`nothing left after clipping ${ids.join(",")}`);


  const proj = geoMercator().fitExtent([[6, 6], [94, 94]], { type: "FeatureCollection", features: feats });
  const path = geoPath().projection(proj);
  const rings = parse(path({ type: "FeatureCollection", features: feats }))
    .filter((r) => r.length > 3)
    .map((r) => rdp(r, eps));
  return rings
    .map((r) => `M${r.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L")}Z`)
    .join("");
};

const out = Object.fromEntries(Object.entries(TARGETS).map(([k, t]) => [k, shape(t)]));

const file = `// AUTO-GENERATED by scripts/gen-country-shapes.mjs from Natural Earth data (world-atlas 110m).
// Each path is fitted to a 0 0 100 100 viewBox. Do not edit by hand — rerun the script.
export const COUNTRY_SHAPES: Record<string, string> = {
${Object.entries(out).map(([k, v]) => `  ${k}: "${v}",`).join("\n")}
};
`;

writeFileSync(new URL("../src/lib/country-shapes.ts", import.meta.url), file);
